options(digits=12)
suppressMessages(library(tsDyn))
y <- as.numeric(log10(lynx))
cat("=== KapShinTest (Kapetanios & Shin 2006 threshold unit root) ===\n")
ks <- try(KapShinTest(y, m=1, include="const")); if(!inherits(ks,"try-error")) print(ks)
cat("\n=== BBCTest (Bec-Ben Salem-Carrasco 2004) ===\n")
bb <- try(BBCTest(y, m=1, testStat="LR")); if(!inherits(bb,"try-error")) print(bb)
cat("\n=== delta.test with default eps grid ===\n")
set.seed(5); print(delta.test(y))
