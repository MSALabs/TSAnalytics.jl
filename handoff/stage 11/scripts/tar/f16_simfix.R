suppressMessages(library(tsDyn))
set.seed(20261014)
B <- c(0.3, 0.5, -0.2, 0.9)
s <- as.numeric(setar.sim(B=B, n=1000, lag=1, type="simul", nthresh=1, Thresh=0, starting=0))
writeLines(c("t,y", sprintf("%d,%.17g", seq_along(s), s)), "fixture_setar_sim.csv")
options(digits=12)
f <- suppressWarnings(setar(s, m=1, thDelay=0)); sm <- summary(f)
cat("n=",length(s)," rows=",length(s)-1,"\n")
cat("th      = ", sprintf("%.17g", as.numeric(tsDyn:::getTh(coef(f)))), "\n")
cat("coef    = ", paste(sprintf("%.17g", head(coef(f),-1)),collapse=", "), "\n")
cat("se      = ", paste(sprintf("%.17g", sm$coefficients[,2]),collapse=", "), "\n")
cat("SSR     = ", sprintf("%.17g", deviance(f)), "\n")
cat("mse     = ", sprintf("%.17g", mse(f)), "\n")
cat("AIC     = ", sprintf("%.17g", AIC(f)), "  BIC=",sprintf("%.17g",BIC(f))," k=",f$k,"\n")
cat("RegProp = ", f$model.specific$RegProp, " nL=",sum(regime(f)==1,na.rm=TRUE)," nH=",sum(regime(f)==2,na.rm=TRUE),"\n")
cat("sha of csv:\n")
