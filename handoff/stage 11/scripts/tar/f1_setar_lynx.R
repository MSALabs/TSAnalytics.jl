suppressMessages(library(tsDyn))
options(digits=12)
y <- log10(lynx)
cat("### SERIES log10(lynx): n =", length(y), " start", start(lynx)[1], "end", end(lynx)[1], "\n")
cat("head6:", paste(sprintf("%.12f", head(y,6)), collapse=" "), "\n")
cat("sum:", sum(y), " mean:", mean(y), "\n\n")

cat("=== selectSETAR(m=2, thDelay=0:1, trace=TRUE) ===\n")
sel <- selectSETAR(y, m=2, thDelay=0:1, trace=TRUE, plot=FALSE)
print(sel)
cat("\n--- sel$bests ---\n"); print(sel$bests)
cat("--- sel names ---\n"); print(names(sel))
cat("--- nrow allTh grid ---\n"); print(dim(sel$allTh)); print(head(sel$allTh, 5)); print(tail(sel$allTh,3))
cat("--- sel$th / sel$firstBests ---\n"); print(sel$th); print(sel$firstBests)

cat("\n\n=== setar(y, m=2, thDelay=1) [textbook] ===\n")
m1 <- setar(y, m=2, thDelay=1)
print(summary(m1))
cat("\n--COEF--\n"); print(coef(m1))
cat("--AIC--", AIC(m1), " BIC--", BIC(m1), " deviance(SSR)--", deviance(m1), " mse--", mse(m1), "\n")
cat("--k--", m1$k, " nobs used--", tsDyn:::getNUsed(m1$str), "\n")
cat("--RegProp--", m1$model.specific$RegProp, "\n")
cat("--regime counts--\n"); print(table(m1$model.specific$regime, useNA="ifany"))
cat("--th--", tsDyn:::getTh(coef(m1)), " thDelay--", m1$model.specific$thDelay, "\n")
cat("--vcov diag--\n"); print(diag(vcov(m1)))
cat("--logLik--", logLik(m1), "\n")
