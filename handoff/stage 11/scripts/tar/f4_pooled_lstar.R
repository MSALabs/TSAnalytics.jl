options(digits=12)
suppressMessages(library(tsDyn))
y <- log10(lynx)
cat("=== POOLED LINEAR AR(2) (tsDyn::linear) ===\n")
lin <- linear(y, m=2)
print(summary(lin))
cat("coef:", paste(sprintf("%.12f",coef(lin)),collapse=" "),"\n")
cat("AIC=",AIC(lin)," BIC=",BIC(lin)," SSR=",deviance(lin)," mse=",mse(lin)," k=",lin$k,"\n")

cat("\n=== LSTAR(y, m=2, thDelay=1) ===\n")
set.seed(42)
ls1 <- lstar(y, m=2, thDelay=1, trace=TRUE, control=list(maxit=5000))
print(summary(ls1))
cat("\ncoef:", paste(sprintf("%.12f",coef(ls1)),collapse=" "),"\n")
cat("names:", paste(names(coef(ls1)),collapse=" "),"\n")
cat("AIC=",AIC(ls1)," BIC=",BIC(ls1)," SSR=",deviance(ls1)," mse=",mse(ls1)," k=",ls1$k,"\n")
cat("vcov diag:", paste(sprintf("%.10g",diag(vcov(ls1))),collapse=" "),"\n")
cat("confint:\n"); print(try(confint(ls1)))
cat("\nmodel.specific names:", paste(names(ls1$model.specific),collapse=" "),"\n")
cat("\n=== isLinear.lstar (linearity test) ===\n")
print(try(isLinear(ls1)))
