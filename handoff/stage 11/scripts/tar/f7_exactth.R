suppressMessages(library(tsDyn))
y <- log10(lynx)
m1 <- suppressWarnings(setar(y, m=2, thDelay=1))
th_exact <- as.numeric(tsDyn:::getTh(coef(m1)))
cat("th exact (17 digits):", sprintf("%.17g", th_exact), "\n")
cat("th printed 12       :", sprintf("%.12f", th_exact), "\n")
a <- suppressWarnings(setar(y, m=2, thDelay=1, th=th_exact))
b <- suppressWarnings(setar(y, m=2, thDelay=1, th=3.31005573775))
cat("exact-th : SSR=",deviance(a)," k=",a$k," AIC=",AIC(a)," nL=",round(a$model.specific$RegProp[1]*112),"\n")
cat("round-th : SSR=",deviance(b)," k=",b$k," AIC=",AIC(b)," nL=",round(b$model.specific$RegProp[1]*112),"\n")
cat("searched : SSR=",deviance(m1)," k=",m1$k," AIC=",AIC(m1)," nL=",round(m1$model.specific$RegProp[1]*112),"\n")
cat("coef(exact)==coef(searched):", isTRUE(all.equal(coef(a),coef(m1))),"\n")
