options(digits=12)
suppressMessages(library(tsDyn))
y <- as.numeric(log10(lynx))
y2 <- y[-1]                 # length 113 -> m=2 gives 111 rows, same as aeon(lag=2,delay=1)
m <- suppressWarnings(setar(y2, m=2, thDelay=0))
cat("tsDyn on y[-1], m=2, thDelay=0:\n")
cat(" th=",sprintf("%.12f",as.numeric(tsDyn:::getTh(coef(m)))),"\n")
cat(" coef:",paste(sprintf("%.12f",head(coef(m),-1)),collapse=" "),"\n")
cat(" SSR=",sprintf("%.12f",deviance(m))," nL=",round(m$model.specific$RegProp[1]*111),"\n")
cat("\ntsDyn on FULL y, m=2, thDelay=0 (112 rows):\n")
m0 <- suppressWarnings(setar(y, m=2, thDelay=0))
cat(" th=",sprintf("%.12f",as.numeric(tsDyn:::getTh(coef(m0)))),"\n")
cat(" coef:",paste(sprintf("%.12f",head(coef(m0),-1)),collapse=" "),"\n")
cat(" SSR=",sprintf("%.12f",deviance(m0)),"\n")
