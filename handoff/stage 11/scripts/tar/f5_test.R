options(digits=12)
suppressMessages(library(tsDyn))
y <- log10(lynx)
cat("=== setarTest defaults ===\n"); print(args(setarTest))
cat("\n=== setarTest(log10(lynx), m=2, thDelay=0:1, nboot=200, trim=0.15, seed=1234) ===\n")
t0<-Sys.time()
st <- setarTest(y, m=2, thDelay=0:1, nboot=200, trim=0.15, test="1vs", seed=1234)
cat("elapsed(s):", as.numeric(difftime(Sys.time(),t0,units="secs")),"\n")
print(st); print(summary(st))
cat("\nSSRs:\n"); print(st$SSRs)
cat("Ftests:\n"); print(st$Ftests)
cat("PvalBoot:\n"); print(st$PvalBoot)
cat("CriticalValBoot:\n"); print(st$CriticalValBoot)
cat("firstBests:\n"); print(st$firstBests); cat("secBests:\n"); print(st$secBests)
cat("nboot:", st$nboot, " dim Ftestboot:", paste(dim(st$Ftestboot),collapse="x"),"\n")
cat("names(st):", paste(names(st),collapse=" "),"\n")
cat("\n=== test 2vs3, nboot=200 ===\n")
