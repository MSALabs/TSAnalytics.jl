options(digits=12)
suppressMessages(library(tsDyn))
cat("=== setar.sim signature ===\n"); print(args(setar.sim))
set.seed(20261014)
## True SETAR(2;1,1): const.L=0.3 phiL=0.5 | const.H=-0.2 phiH=0.9, th=0, thDelay=0
B <- c(0.3, 0.5, -0.2, 0.9)
sim <- setar.sim(B=B, n=1000, lag=1, type="simul", nthresh=1, Thresh=0, starting=0)
cat("class:",class(sim)," length:",length(sim),"\n")
s <- as.numeric(sim)
cat("sim head:", paste(sprintf("%.10f",head(s,5)),collapse=" "),"\n")
cat("mean=",mean(s)," sd=",sd(s)," min=",min(s)," max=",max(s),"\n")
write.csv(data.frame(t=seq_along(s), y=s), "fixture_setar_sim.csv", row.names=FALSE)
cat("\n=== recover with th searched ===\n")
fit <- setar(s, m=1, thDelay=0)
print(summary(fit))
cat("coef:", paste(sprintf("%.12f",coef(fit)),collapse=" "),"\n")
cat("SSR=",deviance(fit)," AIC=",AIC(fit)," RegProp=",fit$model.specific$RegProp,"\n")
cat("\n=== recover with th fixed at TRUE value 0 ===\n")
fit0 <- setar(s, m=1, thDelay=0, th=0)
cat("coef:", paste(sprintf("%.12f",coef(fit0)),collapse=" "),"\n")
cat("SSR=",deviance(fit0),"\n")
cat("\n=== hand-rolled grid on same sim ===\n")
n<-length(s); Y<-s[2:n]; X1<-s[1:(n-1)]
allTh<-sort(unique(X1)); ng<-length(allTh); down<-ceiling(0.15*ng); up<-floor(0.85*ng)
cand<-unique(allTh[seq(down,up,length.out=up-down)])
ssrs<-sapply(cand,function(t){isL<-X1<=t; sum(lm.fit(cbind(cbind(1,X1)*isL,cbind(1,X1)*(!isL)),Y)$residuals^2)})
cat("n cand=",length(cand)," handroll th=",sprintf("%.12f",cand[which.min(ssrs)])," SSR=",sprintf("%.12f",min(ssrs)),"\n")
cat("tsDyn th=",sprintf("%.12f",as.numeric(tsDyn:::getTh(coef(fit)))),"  MATCH:",
    isTRUE(all.equal(cand[which.min(ssrs)], as.numeric(tsDyn:::getTh(coef(fit))))),"\n")
cat("\n=== LSTAR on same sim ===\n")
lf <- try(lstar(s, m=1, thDelay=0, trace=FALSE, control=list(maxit=5000)))
if(!inherits(lf,"try-error")){cat("coef:",paste(sprintf("%.10f",coef(lf)),collapse=" "),"\n");cat("SSR=",deviance(lf)," AIC=",AIC(lf),"\n")}
