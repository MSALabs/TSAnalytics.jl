library(dfms); library(collapse); options(digits=8)
y <- as.matrix(read.csv("fixtureB.csv"))
m <- DFM(y, r=2L, p=1L, em.method="BM", max.iter=200L)
pdf("dfms_plots.pdf", width=9, height=7)
cat("### plot(m, type='joint')      -> "); r<-try(plot(m, type="joint"), silent=TRUE); cat(if(inherits(r,"try-error")) "FAIL" else "OK","\n")
cat("### plot(m, type='individual') -> "); r<-try(plot(m, type="individual", method="all"), silent=TRUE); cat(if(inherits(r,"try-error")) "FAIL" else "OK","\n")
cat("### plot(m, type='residual')   -> "); r<-try(plot(m, type="residual"), silent=TRUE); cat(if(inherits(r,"try-error")) "FAIL" else "OK","\n")
cat("### screeplot(m)               -> "); r<-try(screeplot(m), silent=TRUE); cat(if(inherits(r,"try-error")) "FAIL" else "OK","\n")
ic <- ICr(y, max.r=4L)
cat("### plot(ICr)                  -> "); r<-try(plot(ic), silent=TRUE); cat(if(inherits(r,"try-error")) "FAIL" else "OK","\n")
cat("### screeplot(ICr)             -> "); r<-try(screeplot(ic), silent=TRUE); cat(if(inherits(r,"try-error")) "FAIL" else "OK","\n")
fc <- predict(m, h=12L)
cat("### plot(dfm_forecast)         -> "); r<-try(plot(fc), silent=TRUE); cat(if(inherits(r,"try-error")) "FAIL" else "OK","\n")
dev.off()
cat("\n### summary(m) R2 / variance-decomposition content:\n")
s <- summary(m); cat("  names(summary) =", paste(names(s), collapse=", "), "\n")
print(s$call); cat("  --- F_stats / R2 tables present? ---\n")
for (nm in names(s)) { v<-s[[nm]]; if(is.matrix(v)||is.data.frame(v)) cat("   ", nm, ": dim", paste(dim(v),collapse="x"), "cols:", paste(colnames(v),collapse=","), "\n") }
cat("\n### ICr output:\n"); print(ic$IC)
cat("\n### news() available: "); cat(class(try(news(m, y, t=250L), silent=TRUE)), "\n")
