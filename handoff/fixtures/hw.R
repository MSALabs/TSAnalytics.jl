options(digits=12)
y <- scan("ets_y.csv", quiet=TRUE)
ts_y <- ts(y, frequency=4)
hw <- HoltWinters(ts_y, alpha=0.4, beta=0.1, gamma=0.3, seasonal="additive")
cat("R HoltWinters(alpha=0.4, beta=0.1, gamma=0.3, additive)\n")
cat("  SSE              :", format(hw$SSE, nsmall=8), "\n")
cat("  coef a,b         :", format(round(as.numeric(hw$coefficients[1:2]),10)), "\n")
cat("  coef s1..s4      :", format(round(as.numeric(hw$coefficients[3:6]),10)), "\n")
cat("  fitted xhat[1:4] :", format(round(as.numeric(hw$fitted[1:4,'xhat']),10)), "\n")
cat("  forecast[1:4]    :", format(round(as.numeric(predict(hw, n.ahead=4)),10)), "\n")
