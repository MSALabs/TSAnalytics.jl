@testset "ma_rep: recursion and both references" begin
    m = fit_var(_ifix("var2_p1.csv"), 2)
    Phi = ma_rep(m, 8)
    @test length(Phi) == 9
    @test Phi[1] == Matrix{Float64}(I, 2, 2)              # Φ₀ = I exactly
    @test Phi[2] ≈ m.A[1] atol=1e-14                      # Φ₁ = A₁
    @test Phi[3] ≈ m.A[1] * m.A[1] + m.A[2] atol=1e-13    # Φ₂ = A₁² + A₂
    @test Phi[4] ≈ Phi[3] * m.A[1] + Phi[2] * m.A[2] atol=1e-13   # Φ_{i-j}A_j, not A_jΦ_{i-j}
    @test [Phi[h+1][1, 1] for h in 0:4] ≈
          [1.0, 0.448249746032, 0.230668860843, 0.099275105298, 0.03465341684] atol=1e-10
    @test [Phi[h+1][2, 1] for h in 0:4] ≈
          [0.0, 0.220514094415, 0.199922849949, 0.129947055977, 0.070834656902] atol=1e-10

    Psi = orth_ma_rep(m, 8)
    P = cholesky(Hermitian(m.sigma_df)).L
    @test Psi[1] ≈ P atol=1e-14                           # Ψ₀ = P
    @test Psi[1] ≈ [1.005858110588 0.0; 0.295542029799 0.731322772863] atol=1e-11
    for h in 1:9
        @test Psi[h] ≈ Phi[h] * P atol=1e-12              # Ψ_i = Φ_i P
    end
    # the Σ used is the df-adjusted one, NOT the ML one
    @test !(Psi[1] ≈ cholesky(Hermitian(m.sigma_mle)).L)

    for (key, fx, p, h, tol) in IRF_CASES
        mm = fit_var(_ifix(fx), p)
        r, py = REF_R_IRF[key], REF_PY_IRF[key]
        Phi = ma_rep(mm, h); Psi = orth_ma_rep(mm, h)
        @test length(Phi) == h + 1
        for i in 1:(h + 1)
            @test Phi[i] ≈ _r_ma(r["Phi"])[i] atol=tol
            @test Psi[i] ≈ _r_ma(r["Psi"])[i] atol=tol
            @test Phi[i] ≈ _py_mats(py["ma_rep"])[i] atol=tol
            @test Psi[i] ≈ _py_mats(py["orth_ma_rep"])[i] atol=tol
        end
        @test Psi[1] ≈ _py_mat(r["chol_lower"]) atol=tol
        @test mm.sigma_df ≈ _py_mat(r["Sigma_df"]) rtol=1e-10
    end
    @test_throws ArgumentError ma_rep(m, -1)
    @test length(ma_rep(m, 0)) == 1                       # h = 0 is just Φ₀
end

