# Stage 10.3: impulse responses and forecast error variance decomposition.
#
# Point estimates are DUAL-VERIFIED against vars 1.6.1 and statsmodels 0.15.0,
# which agree with each other to machine precision on every quantity, so any
# disagreement here would be a bug rather than a convention. The analytic
# standard errors have only one software reference (vars has none); they are
# verified independently here by a numerical Jacobian and by a parametric
# bootstrap. Bootstrap bands cannot be matched against vars (different RNG
# stream by design) and are checked by reproducibility and coverage.
#
# Reference values come from test/fixtures/var/refs.jl (REF_R_IRF,
# REF_PY_IRF, VERIFY_IRF_SE), generated by test/verification/var/json_to_jl.py.

if !isdefined(@__MODULE__, :REF_R)
    include(joinpath(@__DIR__, "fixtures", "var", "refs.jl"))
end

_ifix(name) = readdlm(joinpath(@__DIR__, "fixtures", "var", name), ','; skipstart=1)

# statsmodels arrays are [horizon][response][impulse]
_py_mats(a) = [Float64[a[h][i][j] for i in eachindex(a[h]), j in eachindex(a[h][1])]
               for h in eachindex(a)]
_py_mat(M) = Float64[M[i][j] for i in eachindex(M), j in eachindex(M[1])]
# vars' Psi/Phi are [response][impulse][horizon] -- horizon LAST
_r_ma(a) = [Float64[a[i][j][h] for i in eachindex(a), j in eachindex(a[1])]
            for h in eachindex(a[1][1])]
# vars' irf$<impulse> is (h+1) x K, rows = horizon, cols = response
function _r_irf(d, names)
    K = length(names)
    H = length(d[names[1]])
    [Float64[d[names[j]][h][i] for i in 1:K, j in 1:K] for h in 1:H]
end

