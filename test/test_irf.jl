@testset "bootstrap bands: seeded reproducibility" begin
    m = fit_var(_ifix("var2_p1.csv"), 2)
    a = irf(m, 4; boot=true, runs=200, level=95.0, rng=MersenneTwister(4321))
    b = irf(m, 4; boot=true, runs=200, level=95.0, rng=MersenneTwister(4321))
    c = irf(m, 4; boot=true, runs=200, level=95.0, rng=MersenneTwister(9999))
    @test a.lower == b.lower && a.upper == b.upper
    @test a.lower_nonorth == b.lower_nonorth
    @test a.lower != c.lower
    @test a.method === :bootstrap && a.runs == 200 && a.level == 95.0
    for h in 1:5
        @test all(a.lower[h] .<= a.orth[h] .<= a.upper[h])
        @test all(a.lower_nonorth[h] .<= a.nonorth[h] .<= a.upper_nonorth[h])
    end
    # the orthogonalized and non-orthogonalized bands are different objects
    @test a.lower[1] != a.lower_nonorth[1]
    @test a.lower_nonorth[1] == I(2) == a.upper_nonorth[1]   # Φ₀ = I in every replication
    @test a.lower[1][1, 2] == 0.0 == a.upper[1][1, 2]        # P's structural zero
    w = irf(m, 4; boot=true, runs=200, level=99.0, rng=MersenneTwister(4321))
    @test all(w.upper[3] .>= a.upper[3])
    @test all(w.lower[3] .<= a.lower[3])
    # an Int level is accepted and means the same thing
    @test irf(m, 4; boot=true, runs=50, level=95, rng=MersenneTwister(1)).lower ==
          irf(m, 4; boot=true, runs=50, level=95.0, rng=MersenneTwister(1)).lower
    # cumulative bands bracket the cumulative response
    cb = irf(m, 4; boot=true, cumulative=true, runs=100, rng=MersenneTwister(3))
    @test all(cb.lower[5] .<= cb.orth[5] .<= cb.upper[5])
    @test !(cb.upper[5] ≈ a.upper[5])
end

