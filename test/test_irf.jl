# ---- independent verification: a numerical Jacobian of the recursion ----

function _num_irf_stderr(m, H; orth::Bool, eps=1e-6)
    K, p = length(m.names), m.p
    alpha0 = coef_alpha(m)
    S0 = m.sigma_df
    vidx = TSAnalytics._vech_indices(K)
    function f(alpha, S)
        A = [reshape(alpha[((j-1)*K*K+1):(j*K*K)], K, K) for j in 1:p]
        Phi = TSAnalytics._ma_rep(A, H)
        orth || return [vec(M) for M in Phi]
        P = Matrix(cholesky(Hermitian(S)).L)
        return [vec(M * P) for M in Phi]
    end
    Ja = [zeros(K * K, length(alpha0)) for _ in 0:H]
    for a in eachindex(alpha0)
        up = copy(alpha0); up[a] += eps
        dn = copy(alpha0); dn[a] -= eps
        fu, fd = f(up, S0), f(dn, S0)
        for h in 1:(H + 1); Ja[h][:, a] = (fu[h] - fd[h]) / (2eps); end
    end
    Js = [zeros(K * K, length(vidx)) for _ in 0:H]
    if orth
        for (r, (i, j)) in enumerate(vidx)
            Su = copy(S0); Sd = copy(S0)
            Su[i, j] += eps; Sd[i, j] -= eps
            if i != j; Su[j, i] += eps; Sd[j, i] -= eps; end
            fu, fd = f(alpha0, Su), f(alpha0, Sd)
            for h in 1:(H + 1); Js[h][:, r] = (fu[h] - fd[h]) / (2eps); end
        end
    end
    Sa = TSAnalytics._cov_alpha(m)
    Ss = TSAnalytics._cov_sigma(m)
    return [reshape(sqrt.(max.(diag(Ja[h] * Sa * Ja[h]' + (orth ? Js[h] * Ss * Js[h]' : 0I)), 0.0)), K, K)
            for h in 1:(H + 1)]
end

@testset "analytic SEs vs a numerical Jacobian (independent of statsmodels)" begin
    for (fx, p) in (("var2_p1.csv", 2), ("var3_p2.csv", 2), ("var2_p1.csv", 1))
        m = fit_var(_ifix(fx), p)
        H = 5
        an, ao = irf_stderr(m, H), irf_stderr(m, H; orth=true)
        nn, no = _num_irf_stderr(m, H; orth=false), _num_irf_stderr(m, H; orth=true)
        for h in 1:(H + 1)
            @test nn[h] ≈ an[h] atol=1e-8
            @test no[h] ≈ ao[h] atol=1e-8          # checks H, Σ_σ and the /T scaling too
        end
    end
    # the handoff's own numerical-Jacobian run reproduces too
    m = fit_var(_ifix("var2_p1.csv"), 2)
    an = irf_stderr(m, 4)
    for h in 1:5
        @test an[h] ≈ _py_mats(VERIFY_IRF_SE["se_num"])[h] atol=1e-9
    end
    # the Cholesky Jacobian H against a direct finite difference of cholesky
    S = m.sigma_df
    P = Matrix(cholesky(Hermitian(S)).L)
    Hm = TSAnalytics._chol_jacobian(P)
    for (r, (i, j)) in enumerate(TSAnalytics._vech_indices(2))
        Su = copy(S); Sd = copy(S)
        Su[i, j] += 1e-6; Sd[i, j] -= 1e-6
        if i != j; Su[j, i] += 1e-6; Sd[j, i] -= 1e-6; end
        num = vec(Matrix(cholesky(Hermitian(Su)).L) - Matrix(cholesky(Hermitian(Sd)).L)) / 2e-6
        @test Hm[:, r] ≈ num atol=1e-8
    end
end

